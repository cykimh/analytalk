// shadcn(base-nova) 버튼을 스크랩북 테마에 맞춰 고쳤다(DESIGN.md):
// - 키보드 포커스는 링크와 같은 2px 잉크 테두리(outline). 옅은 ring은 종이 위에서 잘 안 보여 쓰지 않는다
