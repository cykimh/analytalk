// 리포트에 남기면 안 되는 표현(공용 단일 출처). 걸린 문단·제목·메모는 저장 전에 지운다(PRD 5장 저장 전 검증 4).
// 대상: 상대 속마음 단정, 애정·관심 점수, 확률 %, 진단명·성격 유형, 민감 추론(성적 지향·건강·종교·정치), 외모 평가, 모욕.
// 숫자는 {{stat:…}} 자리표시자로만 쓰게 하므로 글자로 쓴 %·점수는 모두 막는다.
// g·y 플래그는 쓰지 않는다: test()가 lastIndex를 바꿔 다음 호출 결과가 달라진다.

export const BANNED_PATTERNS: RegExp[] = [
  // 상대 속마음 단정
  /(?:속마음|본심|속으로는)\s*(?:은|이)?\s*(?:분명|확실|사실)/,
  /(?:분명|확실히|틀림없이|100%)[^.!?\n]{0,20}(?:좋아하|좋아해|사랑하|사랑해|싫어하|싫어해|(?:관심|호감)이?\s*(?:있|없)|반했|마음이\s*(?:있|없|식|떠))/,
  /(?:좋아하|사랑하|싫어하)(?:고\s*있)?는\s*(?:게|것이?|거)\s*(?:분명|확실|틀림없)/,
  /마음이\s*(?:식었|떠났|변했)/,
  // 상대 속마음 추측("속으로 ~", "~하는 것 같다·듯하다"). 신조: 패턴은 말해도 속마음은 추측 안 해
  /속으로(?:는|은)?\s*[^.!?\n]{0,15}(?:좋아|사랑|싫어|관심|호감|서운|질투|원하|바라|설레)/,
  /(?:좋아하|사랑하|싫어하|질투하|그리워하|(?:관심|호감|마음|미련)이?\s*(?:있|없))(?:고\s*있)?(?:는|던)\s*(?:(?:것|거)\s*같|듯|모양)/,
  // 애정·관심 점수
  /(?:애정|관심|호감|사랑|썸|궁합|설렘|친밀)\s*(?:지수|점수|레벨|게이지|온도)/,
  /(?:애정|관심|호감|친밀)도\s*(?:는|가|를)?\s*\d/,
  /\d+\s*점\s*만점|만점에\s*\d|\d+\s*\/\s*(?:10|100)(?!\d)/,
  // 확률 %
  /확률/,
  /\d+(?:\.\d+)?\s*(?:%|％|퍼센트)/,
  // 진단명·성격 유형
  /우울증|조울증|양극성|공황\s*장애|ADHD|자폐|경계선\s*성격|인격\s*장애|정신\s*질환|나르시시|소시오패스|사이코패스|강박증|편집증|분리\s*불안|애착\s*(?:유형|장애)|(?:불안|회피)형/i,
  /MBTI|(?<![A-Za-z])[EI][NS][FT][JP](?![A-Za-z])/,
  // 민감 추론: 성적 지향·건강·종교·정치
  /성적\s*(?:지향|취향)|성\s*정체성|동성애|양성애|게이(?!머|밍|트|지)|레즈비언|트랜스젠더/,
  /임신|질병|지병/,
  /종교|신앙|기독교|천주교|불교|이슬람|무교/,
  /정치\s*(?:적\s*)?성향|지지\s*정당|(?:진보|보수)\s*성향|좌파|우파|민주당|국민의힘/,
  // 외모 평가·모욕
  /외모|못생|뚱뚱|살\s*쪘/,
  /병신|븅신|등신|멍청|한심|찌질|또라이|미친놈|미친년/,
];

/** 금지 표현이 하나라도 들었는지 */
export const isBanned = (text: string) => BANNED_PATTERNS.some((re) => re.test(text));
