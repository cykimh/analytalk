// v2.4 Fix 1(2026-11-27 사용자 "3번에서 막던 건 막지 말자"): 속마음·호감·연애 감정 추측과 단정, 호감·케미 점수·순위,
//   놀림·디스·별명, 친구끼리 욕("ㅅㅂ"·"미친놈" 수준)은 말투 인물의 판정으로 둔다(틀려도 좋다). 여기서 막는 것은 넷뿐이다:
//   ① 지어낸 대사 — 따옴표 인용 검사(validate의 inlineQuotesOk)가 맡는다. 여기에는 패턴이 없다
//   ② 혐오·차별(성별·출신·인종·국적·장애·성적 지향 같은 속성을 깎아내리거나 행동의 이유로 대는 말, 혐오 낱말,
//      성적 지향·임신·종교·정치를 사람에게 추측해 붙이는 말)과 성적인 묘사
//   ③ 진단명을 사실처럼 붙이는 것(대화 주제로 나온 진단명은 된다)
//   ④ 자해·폭력을 부추기는 말
//   그리고 글자로 쓴 퍼센트(비율 통계는 {{stat:…}} 자리표시자로만 쓴다. 지어낸 통계가 사실처럼 보이지 않게).
// 민감한 낱말이 나오는 것만으로는 막지 않는다(원문에 나온 이야기를 전하는 것은 된다). 그 속성을 사람에게 붙이거나 깎아내리는 꼬리만 본다.
// g·y 플래그는 쓰지 않는다: test()가 lastIndex를 바꿔 다음 호출 결과가 달라진다.
// 넓게 막는 쪽이라 정상 문장도 지워질 수 있다("부산 출신이라 사투리를 쓴다"처럼 속성을 행동의 이유로 대는 말은 비하가 아니어도 지운다).

/** 성적 지향·성 정체성 */
const ORIENTATION =
  "(?:성적\\s*(?:지향|취향)|성\\s*정체성|동성애자?|양성애자?|게이(?!머|밍|트|지)|레즈비언|레즈(?!비언)|트랜스젠더)";
/** 민감 속성(성적 지향·건강·임신·종교·정치). 사람에게 추측·단정으로 붙이면 막는다 */
const SENSITIVE = `(?:${ORIENTATION}|임신|지병|질병|종교|신앙|기독교인?|천주교인?|불교\\s*신자|무슬림|무교|정치\\s*(?:적\\s*)?성향|지지\\s*정당|(?:진보|보수)\\s*(?:성향|적)|(?:민주당|국민의힘)\\s*지지자?)`;
/** 그 속성을 그 사람에게 붙이는 꼬리: (조사·서술) + 추측·단정. 속성 바로 뒤에 붙을 때만 본다 */
const ATTRIBUTE_TAIL =
  "(?:인|일|이|가|한|했|하는|했던|하고\\s*있는|중인)?\\s*(?:(?:이|가)\\s*)?(?:(?:있|없)(?:는|어|을)?\\s*)?(?:(?:것|거)\\s*같|듯|모양|(?:가|나)\\s*봐|가능성|(?:게\\s*)?(?:분명|확실|틀림없)|보여|보이|느껴)";
/** 성적 지향을 그 사람에게 그대로 단정하는 꼬리(~다·~야·~예요·~입니다·~임·~라서·~니까, ~ 같-).
 *  "철수는 게이다"처럼 맨 단정이 "~인 것 같다"보다 약하게 걸리지 않도록 따로 둔다. "게이머다"·"게이 친구 얘기"는 걸리지 않는다 */
const ORIENTATION_TAIL = "(?:(?:이)?(?:다|야|예요|이에요|입니다|임|라서|니까)(?![가-힣])|\\s*같)";

/** 깎아내리기 쉬운 속성: 성별·출신 지역·인종·국적·장애·성적 지향 */
const PROTECTED =
  `(?:여자|남자|여성|남성|여자애|남자애|계집애?|전라도|경상도|충청도|강원도|제주도|[가-힣]{1,4}\\s*출신|흑인|백인|동양인|동남아|조선족|중국인|일본인|외국인|다문화|혼혈|장애인|${ORIENTATION})`;
/** 속성을 행동의 이유로 대거나(~라서·~이니까·~답게) 견주는(~처럼·~같아서) 꼬리 */
const PROTECTED_TAIL =
  "(?:(?:이)?라서|(?:이)?니까|(?:이)?라\\s*(?:그런|저런|그렇|저렇|그래|저래|저렇게|그렇게)|(?:이)?기\\s*때문|답게|다운|다워|\\s*처럼|\\s*같(?:아서|아|은|이|다|네))";

/** 진단명(정신·발달) */
const DIAGNOSIS =
  "(?:우울증|조울증|양극성\\s*장애|공황\\s*장애|ADHD|자폐(?:증)?|경계선\\s*성격\\s*장애|인격\\s*장애|정신\\s*질환|정신병|소시오패스|사이코패스|강박증|편집증|분리\\s*불안|애착\\s*장애|나르시시스트)";
/** 진단명을 그 사람에게 사실·추측으로 붙이는 꼬리(~이다·~가 있다·~환자·~이 의심된다·~인 것 같다·~ 같다·~라서·~ 확정·~ 걸렸다).
 *  앞에 \s*가 붙으므로 "ADHD 같다"·"소시오패스 확정"처럼 띄어 쓴 꼬리도 잡는다. "우울증 기사"처럼 주제로 나온 것은 둔다 */
const DIAGNOSIS_TAIL =
  "(?:이다|다(?![가-힣])|이야|야(?![가-힣])|이에요|예요|입니다|이네|네(?![가-힣])|임|이\\s*있|가\\s*있|이\\s*심하|가\\s*심하|환자|기질|끼가|이\\s*분명|가\\s*분명|임이?\\s*(?:분명|틀림)|인\\s*(?:게|것|거|듯|모양)|일\\s*(?:것|거|수도|가능성)|(?:이|가)\\s*의심|(?:이|가)\\s*확실|맞(?:다|네|아|는)|같(?:다|아|은|네)|(?:이)?라서|확정|걸(?:렸|린|려))";

export const BANNED_PATTERNS: RegExp[] = [
  // 글자로 쓴 퍼센트(비율 통계는 자리표시자로만)
  /\d+(?:\.\d+)?\s*(?:%|％|퍼센트)/,
  // ③ 진단명을 사람에게 붙이기
  new RegExp(`${DIAGNOSIS}\\s*${DIAGNOSIS_TAIL}`, "i"),
  // ② 민감 속성(성적 지향·건강·임신·종교·정치) + 바로 붙은 추측·단정·견줌 꼬리
  new RegExp(`${SENSITIVE}${ATTRIBUTE_TAIL}`),
  // ② 성적 지향을 맨 단정으로 붙이기("철수는 게이다", "민지는 동성애자야", "레즈비언이라서")
  new RegExp(`${ORIENTATION}${ORIENTATION_TAIL}`),
  // ② 속성을 행동의 이유로 대거나 견주어 깎아내리기("여자라서 약속을 못 지킨다", "전라도 출신이라 저렇다", "장애인처럼")
  new RegExp(`${PROTECTED}${PROTECTED_TAIL}`),
  // ② 혐오 낱말(집단을 깎아내리는 말). 친구끼리 욕(ㅅㅂ·미친놈·병신 수준)은 여기 넣지 않는다
  //   "애자"는 앞에 한글이 붙지 않을 때만 본다("동성애자"·"연애자"를 잘못 지우지 않게)
  /김치녀|된장녀|한남충|한남(?![가-힣])|맘충|급식충|틀딱|똥꼬충|짱깨|쪽바리|흑형|깜둥|홍어\s*(?:족|새끼|들)|정신병자|(?<![가-힣])애자(?:야|다|냐|들)?(?![가-힣])|장애\s*새끼|저능아|정박아|벙어리|귀머거리|절름발이|(?:여자|계집)\s*(?:주제에|따위)|(?:남자|여자)\s*새끼(?:들)?\s*(?:는|들은)\s*(?:다|원래)/,
  // ② 성적인 묘사
  /성관계|섹스|야한|야하게|야해(?:서|요)?|19금|야동|자위(?!대)|알몸|나체|몸매|옷을?\s*벗|뜨거운\s*밤|잠자리를?\s*(?:같이|함께|가지)|(?:침대|모텔|러브호텔)(?:에서|로|에)?\s*[^.!?\n]{0,12}(?:밤|뒹굴|같이|함께|둘이|보낼|보냈)|(?:같이|함께|둘이)\s*[^.!?\n]{0,8}(?:침대|모텔)/,
  // ④ 자해·폭력 부추김(웃겨 죽겠다·죽어라 공부했다 같은 관용구는 둔다)
  /죽어\s*(?:버려|버리|줘|라(?=\s*[.!~]|\s*$))|(?:그냥|차라리|빨리|당장|좀)\s*죽어|죽어야\s*(?:해|한다|돼|된다|정신)|뒤져\s*(?:버려|라)|뒤지라|자살(?:해\s*(?:라|버려|버리)|하(?:라|든지|세요)|이라도)|자해(?:라도|해\s*(?:라|버려)|하(?:라|든지))|목을?\s*매\s*(?:달아|라|버려)|목\s*매달아|손목을?\s*(?:그어|긋)|뛰어\s*내려\s*(?:라|버려)|죽여\s*(?:버[려리릴린]|야|라|줘)|때려\s*(?:줘|주|야|버[려리릴린]|죽)|(?:패|두들겨\s*패|쥐어\s*패)\s*(?:버려|버리|줘야|야\s*(?:한다|해|돼|정신))|한\s*대\s*(?:때려|쳐|패|맞아야|맞아\s*봐야)|칼로\s*찔러|찔러\s*(?:버려|죽)|불\s*질러\s*(?:버려|버리)/,
];

/** 금지 표현이 하나라도 들었는지 */
export const isBanned = (text: string) => BANNED_PATTERNS.some((re) => re.test(text));
