// 리포트에 남기면 안 되는 표현(공용 단일 출처). 걸린 문단·제목·메모는 저장 전에 지운다(PRD 5장 저장 전 검증 4).
// 대상: 상대 속마음 단정, 애정·관심 점수, 확률 %, 진단명·성격 유형, 민감 속성 추측·단정(성적 지향·건강·임신·종교·정치), 외모 평가, 모욕.
// 민감한 낱말이 나오는 것만으로는 막지 않는다(원문에 나온 이야기를 전하는 것은 된다). 그 속성을 사람에게 붙이는 추측·단정만 막는다.
// 숫자는 {{stat:…}} 자리표시자로만 쓰게 하므로 글자로 쓴 %·점수는 모두 막는다.
// g·y 플래그는 쓰지 않는다: test()가 lastIndex를 바꿔 다음 호출 결과가 달라진다.
// 넓게 막는 쪽이라 정상 문단도 지워질 수 있다. 골든셋 평가(Task 16)에서 문단 삭제율을 확인한다.
// v2.4: 리포트가 행동·역할에 과감한 판정("이 방의 실세는 ○○이다"·"범인은 ○○다"·"~임이 틀림없다"·"~인 것 같다")을 내린다.
//   이런 판정은 막지 않고 속마음·호감 단정만 잡는다: '확률'은 연애·속마음 예측에만, "사실은 ○○를 좋아한다" 같은 단정은 새로 막는다.
//   멤버를 대상으로 한 호감 단정("민수는 사실 으리를 좋아한다")은 이름을 아는 isBannedAbout이 잡는다(검증만 쓴다).

// 같은 뜻의 다른 말투(D7): 감정·애정 말 + 추측 꼬리("~나 봐요"·"~것 같아요"·"~듯해요"·"~어 보여요"·"~이 느껴져요")
/** "하다"가 붙는 감정 말의 머리(좋아하·서운해하·실망하 …) */
const FEEL_HA = "(?:좋아|사랑|싫어|질투|그리워|서운해|섭섭해|귀찮아|미안해|외로워|부담스러워|아쉬워|반가워|기뻐|실망)";
/** 받침이 붙어 한 글자가 된 감정 말(설렌·삐졌·상처받은 …) */
const FEEL_FORMS = "(?:설레는|설렌|설렜|삐지는|삐진|삐졌|삐치는|삐친|삐쳤|상처\\s*받(?:은|았|는)|신경\\s*(?:쓰는|쓴|썼))";
/** 감정 상태(화가 난·서운한·귀찮아 …). 화는 앞에 한글이 없을 때만("영화나 봐요"·"전화나 봐"의 화는 아니다) */
const FEEL_STATE =
  "(?:(?:(?<![가-힣])화|짜증)가?\\s*(?:났|난|나)|기분이?\\s*(?:상했|상한|상해|나빴|나쁜|나빠)|서운(?:한|했|해)|섭섭(?:한|했|해)|귀찮(?:은|았|아)|외로(?:운|웠|워))";
/** 추측 꼬리 */
const GUESS = "(?:(?:던|었던|나|는가)?\\s*(?:(?:것|거)\\s*같|듯|모양|봐|눈치))";

/** 민감 속성(성적 지향·건강·임신·종교·정치)을 가리키는 말 */
const SENSITIVE =
  "(?:성적\\s*(?:지향|취향)|성\\s*정체성|동성애자?|양성애자?|게이(?!머|밍|트|지)|레즈비언|트랜스젠더|임신|지병|질병|종교|신앙|기독교인?|천주교인?|불교\\s*신자|무슬림|무교|정치\\s*(?:적\\s*)?성향|지지\\s*정당|(?:진보|보수)\\s*(?:성향|적)|(?:민주당|국민의힘)\\s*지지자?)";
/** 그 속성을 그 사람에게 붙이는 꼬리: (조사·서술) + 추측·단정. 속성 바로 뒤에 붙을 때만 본다 */
const ATTRIBUTE_TAIL =
  "(?:인|일|이|가|한|했|하는|했던|하고\\s*있는|중인)?\\s*(?:(?:이|가)\\s*)?(?:(?:있|없)(?:는|어|을)?\\s*)?(?:(?:것|거)\\s*같|듯|모양|(?:가|나)\\s*봐|가능성|(?:게\\s*)?(?:분명|확실|틀림없)|보여|보이|느껴)";

/** 호감·연애 감정을 단정하는 서술(좋아한다·사랑한다·반했다·짝사랑·관심/호감/마음이 있다) */
const AFFECTION =
  "좋아하|좋아해|좋아한|사랑하|사랑해|사랑한|짝사랑|반했|반한|반해|설레|(?:관심|호감|마음)이?\\s*(?:있|생겼|가)";

export const BANNED_PATTERNS: RegExp[] = [
  // 상대 속마음 추측: 감정 말 + 추측 꼬리 / 감정 상태 + 추측·"보여" / 감정 명사 + "느껴·보여"
  new RegExp(`${FEEL_HA}(?:하는|한|했던|하던|하고\\s*있는|하나|했나|하는가)\\s*(?:(?:것|거)\\s*같|듯|모양|봐|눈치)`),
  new RegExp(`${FEEL_FORMS}${GUESS}`),
  new RegExp(`${FEEL_STATE}(?:${GUESS}|\\s*(?:보여|보이))`),
  /(?:관심|호감|마음|미련|애정)이?\s*(?:있|없)(?:어|는|던|었던|나)?\s*(?:보여|보이|(?:것|거)\s*같|듯|봐|모양)/,
  /(?:호감|관심|애정|설렘|서운함|섭섭함|질투|미련|사랑)이?\s*(?:느껴|보여|보이)/,
  // 숫자 없이 높낮이로 말하는 애정·관심 점수("애정도가 높아요")
  /(?:애정|관심|호감|친밀|설렘)\s*도\s*(?:가|는|를)?\s*(?:높|낮|올라|오르|떨어|최고|상승|하락|만렙)/,
  // 상대 속마음 단정
  /(?:속마음|본심|속으로는)\s*(?:은|이)?\s*(?:분명|확실|사실)/,
  // "사실은·알고 보면 ~를 좋아한다"처럼 숨은 호감을 밝히는 투(v2.4). 과감한 판정 말투에서 나오기 쉽다
  new RegExp(
    `(?:사실은|실은|알고\\s*보면|알고\\s*보니)\\s*[^.!?\\n]{0,20}(?:${AFFECTION})`,
  ),
  /(?:분명|확실히|틀림없이|100%)[^.!?\n]{0,20}(?:좋아하|좋아해|사랑하|사랑해|싫어하|싫어해|(?:관심|호감)이?\s*(?:있|없)|반했|마음이\s*(?:있|없|식|떠))/,
  /(?:좋아하|사랑하|싫어하)(?:고\s*있)?는\s*(?:게|것이?|거)\s*(?:분명|확실|틀림없)/,
  /마음이\s*(?:식었|떠났|변했)/,
  // 상대 속마음 추측("속으로 ~", "~하는 것 같다·듯하다"). 신조: 패턴은 말해도 속마음은 추측 안 해
  /속으로(?:는|은)?\s*[^.!?\n]{0,15}(?:좋아|사랑|싫어|관심|호감|서운|질투|원하|바라|설레)/,
  /(?:좋아하|사랑하|싫어하|질투하|그리워하|(?:관심|호감|마음|미련)이?\s*(?:있|없))(?:고\s*있)?(?:는|던)\s*(?:(?:것|거)\s*같|듯|모양)/,
  // 애정·관심 점수
  /(?:애정|관심|호감|사랑|썸|궁합|설렘|친밀)\s*(?:지수|점수|레벨|게이지|온도)/,
  /(?:애정|관심|호감|친밀)도\s*(?:는|가|를)?\s*\d/,
  /\d+\s*점\s*만점|만점에\s*\d/,
  // n/10은 점수 문맥(앞에 애정·호감·관심·점수, 뒤에 점·만점)에서만. "3/10에 만났어요" 같은 날짜는 둔다
  /(?:애정|호감|관심|점수)\s*\d+\s*\/\s*(?:10|100)(?!\d)|\d+\s*\/\s*(?:10|100)\s*(?:점|만점)/,
  // 확률: 연애·관계·속마음의 앞날을 점치는 것만(v2.4. "범인일 확률이 높다" 같은 판정은 둔다). 숫자 %는 아래에서 따로 막는다
  /(?:사귈|고백할|이어질|좋아할|사랑할|연락할|헤어질|결혼할|만날|반할|넘어올)\s*확률|(?:사랑|썸|짝사랑|호감|연애|진심|관심|마음)(?:일|이)?\s*확률|확률\s*(?:은|이|도|이\s*높|이\s*낮)?\s*(?:\{\{|\d)|확률[^.!?\n]{0,8}(?:속마음|마음|감정|호감|진심|사랑|연애|썸)/,
  /\d+(?:\.\d+)?\s*(?:%|％|퍼센트)/,
  // 진단명·성격 유형
  /우울증|조울증|양극성|공황\s*장애|ADHD|자폐|경계선\s*성격|인격\s*장애|정신\s*질환|나르시시|소시오패스|사이코패스|강박증|편집증|분리\s*불안|애착\s*(?:유형|장애)|(?:불안|회피)형/i,
  /MBTI|(?<![A-Za-z])[EI][NS][FT][JP](?![A-Za-z])/,
  // 민감 속성(성적 지향·건강·임신·종교·정치) + 바로 붙은 추측·단정 꼬리
  new RegExp(`${SENSITIVE}${ATTRIBUTE_TAIL}`),
  // 건강 상태 추측: "아픈 것 같아요", "몸이 안 좋은 듯해요"
  /(?:아픈|아팠던|몸이\s*안\s*좋은|병이\s*있는)\s*(?:(?:것|거)\s*같|듯|모양|가능성)/,
  // 외모 평가·모욕
  /외모|못생|뚱뚱|살\s*쪘/,
  /병신|븅신|등신|멍청|한심|찌질|또라이|미친놈|미친년/,
];

/** 금지 표현이 하나라도 들었는지 */
export const isBanned = (text: string) => BANNED_PATTERNS.some((re) => re.test(text));

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
/** 이름과 호감 말 사이에 올 수 있는 꾸밈말(몰래·은근히·사실…) */
const AFFECTION_ADVERB = "(?:정말|진짜|몰래|남몰래|혼자|많이|은근히|은근|꽤|좀|무척|엄청|아주|너무|사실|분명|확실히|오래|계속)";
/**
 * 멤버를 대상으로 한 호감 단정(v2.4): "<이름>을/를/한테/에게 (꾸밈말) 좋아한다·반했다·관심이 있다". 과감한 판정 말투에서
 * "민수는 사실 으리를 좋아한다"처럼 속마음을 사실로 쓰는 문장을 막는다. 이름 바로 뒤 조사와 꾸밈말만 건너뛴다
 * ("민지를 놀리는 걸 좋아한다"처럼 행동을 좋아하는 것은 걸리지 않는다)
 */
export function isBannedAbout(text: string, members: readonly string[]): boolean {
  return members.some((name) => {
    if (name.trim() === "") return false;
    const re = new RegExp(`${escapeRe(name)}(?:을|를|이를|에게|한테|께|더러)(?:\\s*${AFFECTION_ADVERB})*\\s*(?:${AFFECTION})`);
    return re.test(text);
  });
}
