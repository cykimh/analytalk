// 자주 쓰는 단어(v2.9): 글 메시지를 단어로 나눈다. 브라우저 Worker의 통계 계산(computeStats)이 쓰는 순수 함수다.
// 단어 = 두 글자 이상의 한글 덩어리 또는 영어 덩어리(소문자로). 숫자는 단어가 아니라서 전화·계좌·카드·주민번호는 처음부터 들어오지 않고,
// 링크·이메일은 나누기 전에 지운다. 한글 단어 끝의 흔한 조사는 떼고(남는 말이 두 글자 이상일 때만), 불용어·감탄·웃음(ㅋ·ㅎ는 한글 음절이 아니라 애초에 빠진다)은 뺀다.
// 멤버 이름은 빼지 않는다(재미 요소, 2026-11-27 사용자 승인). 단어 목록은 stats에 실려 DB에 30일 남고 공유 링크에 보인다

const URL_RE = /https?:\/\/[^\s<>"']+|www\.[^\s<>"']+/gi;
const EMAIL_RE = /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g;
/** 숫자 바로 뒤의 덩어리(7시에·3pm 같은 단위)는 단어로 보지 않는다 */
const TOKEN_RE = /(?<![0-9가-힣])[가-힣]{2,}|(?<![0-9A-Za-z])[A-Za-z]{2,}/g;
/** 저장하는 단어의 최대 글자 수(이보다 길면 띄어 쓰지 않은 문장이라 뺀다) */
export const WORD_MAX_CHARS = 20;

/** 뗄 조사(긴 것부터). 이·가는 '고양이'·'아이'처럼 말의 일부인 때가 많아 떼지 않는다 */
const PARTICLES = ["에서", "으로", "한테", "에게", "까지", "부터", "이랑", "처럼", "보다", "은", "는", "을", "를", "도", "의", "에", "로", "랑", "만", "과", "와", "야"];

/** 불용어: 대명사·접속·부사·흔한 동사 꼴·감탄. 너무 흔해 그 사람의 말버릇을 가린다 */
const STOPWORDS = new Set([
  // 접속·부사
  "그냥", "근데", "그런데", "그래서", "그리고", "그러니까", "그럼", "그래", "그래도", "진짜", "정말", "너무", "완전", "약간", "조금", "많이",
  "이제", "지금", "다시", "계속", "아직", "이미", "벌써", "일단", "혹시", "그렇게", "이렇게", "저렇게", "어떻게", "왜냐면", "아니면", "또는",
  // 때
  "오늘", "내일", "어제", "요즘", "이따", "나중",
  // 대명사
  "우리", "나도", "너도", "나는", "내가", "너는", "니가", "네가", "저는", "제가", "그거", "이거", "저거", "그게", "이게", "저게", "여기", "거기", "저기", "뭐야", "뭔가", "누구",
  // 흔한 동사·형용사 꼴
  "있어", "없어", "같아", "했어", "하는", "하고", "해서", "하면", "했는데", "하자", "해야", "하지", "했다", "한다", "있는", "없는", "같은", "있고", "그거야", "아니", "아니야", "맞아", "그치", "그니까", "좋아", "알아", "몰라",
  "어때", "봤어", "됐어", "왔어", "갔어", "할게", "갈게", "했지", "있지", "그건", "이건", "어디", "언제", "뭐해",
  // 감탄·대답
  "아아", "오오", "우와", "와우", "음음", "에휴", "아휴", "으악", "아이고", "어머", "오호", "응응", "웅웅", "네네", "넹넹", "넵넵",
  // 영어
  "the", "and", "you", "to", "of", "in", "is", "it", "me", "my", "so", "lol", "omg", "ok",
]);

/** 한글 단어 끝의 조사를 뗀다(남는 말이 두 글자 이상일 때만) */
function stem(word: string): string {
  for (const p of PARTICLES) {
    if (word.endsWith(p) && word.length - p.length >= 2) return word.slice(0, -p.length);
  }
  return word;
}

/** 글 메시지 하나의 단어들(센 순서대로, 같은 단어가 여러 번 나오면 여러 번) */
export function wordsOf(text: string): string[] {
  const body = text.replace(URL_RE, " ").replace(EMAIL_RE, " ");
  const out: string[] = [];
  for (const [raw] of body.matchAll(TOKEN_RE)) {
    const word = /^[A-Za-z]/.test(raw) ? raw.toLowerCase() : stem(raw);
    if (word.length > WORD_MAX_CHARS || STOPWORDS.has(word)) continue;
    out.push(word);
  }
  return out;
}

/** 단어 수 표 → 두 번 이상 쓴 단어 TOP n(많은 순, 같으면 가나다·알파벳 순) */
export function topOf(counts: Map<string, number>, n: number): [string, number][] {
  return [...counts]
    .filter(([, c]) => c >= 2)
    .sort(([a, x], [b, y]) => y - x || (a < b ? -1 : a > b ? 1 : 0))
    .slice(0, n);
}
